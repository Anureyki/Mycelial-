#!/usr/bin/env python3
"""Regenerate data/bundle.js from the canonical JSON files so index.html also opens from file:// (no fetch).
Edit data/points.json (or hand.json / meridians.json / layers.json), then run: python3 tools/bundle.py"""
import json, os
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R=lambda p:os.path.join(ROOT,p)
names=['points','meridians','layers','figure','hand']+(['foot'] if os.path.exists(R('data/foot.json')) else [])
B={n:json.load(open(R(f'data/{n}.json'),encoding='utf-8')) for n in names}
win=json.load(open(os.path.join(os.path.dirname(os.path.dirname(ROOT)),'config/ati/organ_clock_windows.json')))
B['clock_windows']=[{k:w[k] for k in ('start','end','organ','organ_display','element','branch','branch_display')} for w in win['windows']]
open(R('data/bundle.js'),'w',encoding='utf-8').write('/* generated by tools/bundle.py from data/*.json - do not edit */\nwindow.MBODY='+json.dumps(B,ensure_ascii=False,separators=(',',':'))+';\n')
print('bundle.js',os.path.getsize(R('data/bundle.js')),'bytes')
